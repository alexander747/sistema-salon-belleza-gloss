export type TipoMovimiento = 'Servicio' | 'Producto';
export type EstadoCobro = 'PAGADO' | 'FIADO' | 'PARCIAL';

/**
 * One sale LINE (service or product) in the "Movimientos" sheet.
 * Sale-level amounts (total venta / pagado / fiado / pendiente / estado) are
 * repeated on every line of the same sale so a row is self-contained.
 */
export interface RegistroMovimiento {
  /** YYYY-MM-DD (fecha de negocio Colombia). */
  fecha: string;
  cliente: string;
  empleada: string;
  tipo: TipoMovimiento;
  /** Service or product name. */
  concepto: string;
  cantidad: number;
  precioUnitario: number;
  /** Precio unitario × cantidad (gross, before sale-level discounts). */
  subtotal: number;
  /** Actual sale total (`valorFinal`, falling back to `montoTotal`). */
  totalVenta: number;
  /** Σ payments received for the sale (including later debt collections). */
  montoPagado: number;
  /** Σ payments received on/around the sale's business date (at sale time). */
  montoPagadoAlVender: number;
  /** Σ payments received AFTER the sale's business date (fiado collections). */
  montoCobradoDespues: number;
  /** Fiado generated by the sale (`montoFiado` snapshot, legacy fallback to pending). */
  montoFiado: number;
  /** Current outstanding debt of the sale. */
  montoPendiente: number;
  estadoCobro: EstadoCobro;
  /** Last collection date (YYYY-MM-DD) received AFTER the sale; null if none. */
  fechaUltimoCobro: string | null;
}

/** Period fiado aggregates for the FIADO block in the summary sheet. */
export interface FiadoResumen {
  /** Σ fiado generated by the period's sales (`montoFiado` snapshot, legacy fallback). */
  generado: number;
  /** Σ collected from that same fiado (generated − still pending, clamped at 0). */
  cobrado: number;
  /** Σ current pending debt of the period's sales. */
  pendiente: number;
}

