function round2(n: number): number {
  return Math.round(n * 100) / 100;
}

function toDate(value: Date | string | null | undefined): Date | null {
  if (value == null) return null;
  const date = value instanceof Date ? value : new Date(value);
  return Number.isNaN(date.getTime()) ? null : date;
}

function sumPagos(pagos: PagoTransaccionEntity[] | undefined): number {
  return (pagos ?? []).reduce((sum, pago) => sum + Number(pago.monto ?? 0), 0);
}

/** Formats a date-only value (caja `fechaCaja`) as YYYY-MM-DD, avoiding the
 *  Colombia shift that would move a midnight-UTC Date to the previous day. */
function dateOnlyString(date: Date): string {
  const y = date.getUTCFullYear();
  const m = String(date.getUTCMonth() + 1).padStart(2, '0');
  const d = String(date.getUTCDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

/** Collection date of one payment: its caja business date when loaded, else
 *  the payment timestamp (Colombia). */
function fechaPago(pago: PagoTransaccionEntity): string | null {
  const fechaCaja: unknown = pago.caja?.fechaCaja;
  if (fechaCaja instanceof Date) return dateOnlyString(fechaCaja);
  if (typeof fechaCaja === 'string' && fechaCaja.length > 0) {
    return fechaCaja.slice(0, 10);
  }
  const creadoEn = toDate(pago.creadoEn);
  return creadoEn ? getColombiaDateString(creadoEn) : null;
}

/**
 * Splits the sale's payments into paid-at-sale (on or before the sale's
 * business date) and collected-later (after it) amounts, and returns the last
 * later collection date. Payments without a resolvable date fall into the
 * at-sale bucket so the split always adds up to `Σ pagos`.
 */
function dividirPagos(
  pagos: PagoTransaccionEntity[] | undefined,
  fechaVenta: string,
  montoPagado: number,
): { alVender: number; despues: number; ultimaFecha: string | null } {
  let despues = 0;
  let ultimaFecha: string | null = null;

  for (const pago of pagos ?? []) {
    const fecha = fechaPago(pago);
    if (fecha != null && fecha > fechaVenta) {
      despues += Number(pago.monto ?? 0);
      if (ultimaFecha == null || fecha > ultimaFecha) {
        ultimaFecha = fecha;
      }
    }
  }

  despues = round2(despues);
  return {
    alVender: round2(montoPagado - despues),
    despues,
    ultimaFecha,
  };
}

function calcularEstadoCobro(montoPagado: number, montoPendiente: number): EstadoCobro {
  if (montoPendiente <= 0) return 'PAGADO';
  if (montoPagado <= 0) return 'FIADO';
  return 'PARCIAL';
}

/**
 * Expands one registro into its sale lines (services and products).
 * Service items are stored one row per unit, so identical per-unit rows are
 * grouped back into a single line with `cantidad`. Legacy registros without
 * item rows fall back to one aggregate line per category so the workbook never
 * silently drops money.
 */
export function registroAMovimientos(registro: RegistroServicioEntity): RegistroMovimiento[] {
  // Business date (backfill-aware) matches the period query filter.
  const fechaNegocio = toDate(registro.fechaHora) ?? toDate(registro.creadoEn);
  const fecha = fechaNegocio ? getColombiaDateString(fechaNegocio) : getColombiaDateString();

  const montoPendiente = Math.max(0, Number(registro.montoPendiente ?? 0));
  const montoPagado = round2(sumPagos(registro.pagos));
  const montoFiado = round2(
    Math.max(
      0,
      registro.montoFiado != null ? Number(registro.montoFiado) : montoPendiente,
    ),
  );
  const totalVenta =
    registro.valorFinal != null
      ? Number(registro.valorFinal)
      : Number(registro.montoTotal ?? 0);
  const estadoCobro = calcularEstadoCobro(montoPagado, montoPendiente);
  // Fiado collected later must not look like it was paid on the sale's date:
  // split the payments and keep the last collection received after the sale.
  const pagosDivididos = dividirPagos(registro.pagos, fecha, montoPagado);

  const base = {
    fecha,
    cliente: registro.cliente?.nombre ?? `Cliente #${registro.clienteId}`,
    empleada: registro.usuario?.nombre ?? `Empleada #${registro.usuarioId}`,
    totalVenta,
    montoPagado,
    montoPagadoAlVender: pagosDivididos.alVender,
    montoCobradoDespues: pagosDivididos.despues,
    montoFiado,
    montoPendiente,
    estadoCobro,
    fechaUltimoCobro: pagosDivididos.ultimaFecha,
  };

  const rows: RegistroMovimiento[] = [];

  // ── Services: group the per-unit rows into one line per distinct service ──
  interface GrupoServicio {
    concepto: string;
    precioUnitario: number;
    cantidad: number;
  }
  const grupos = new Map<string, GrupoServicio>();
  for (const item of registro.serviciosItems ?? []) {
    const precioUnitario = Number(item.precioServicio ?? 0);
    const concepto = String(item.nombreServicio ?? 'Servicio');
    const key = `${item.servicioId}|${concepto}|${precioUnitario}`;
    const grupo = grupos.get(key);
    if (grupo) {
      grupo.cantidad += 1;
    } else {
      grupos.set(key, { concepto, precioUnitario, cantidad: 1 });
    }
  }
  for (const grupo of grupos.values()) {
    rows.push({
      ...base,
      tipo: 'Servicio',
      concepto: grupo.concepto,
      cantidad: grupo.cantidad,
      precioUnitario: grupo.precioUnitario,
      subtotal: round2(grupo.precioUnitario * grupo.cantidad),
    });
  }

  // ── Products: one row per stored product line ──
  for (const rp of registro.productosVendidos ?? []) {
    const cantidad = Number(rp.cantidad ?? 0);
    const precioUnitario = Number(rp.precioVentaUnitario ?? 0);
    rows.push({
      ...base,
      tipo: 'Producto',
      concepto: rp.producto?.nombre ?? `Producto #${rp.productoId}`,
      cantidad,
      precioUnitario,
      subtotal:
        rp.subtotal != null ? Number(rp.subtotal) : round2(precioUnitario * cantidad),
    });
  }

  // ── Legacy fallbacks: no item rows but the sale still totals money ──
  if (grupos.size === 0) {
    const totalServicios = Number(registro.totalServicios ?? 0);
    if (totalServicios > 0) {
      rows.push({
        ...base,
        tipo: 'Servicio',
        concepto: registro.descripcionServicio?.trim() || 'Servicios',
        cantidad: 1,
        precioUnitario: totalServicios,
        subtotal: totalServicios,
      });
    }
  }
  if ((registro.productosVendidos ?? []).length === 0) {
    const totalProductos = Number(registro.totalProductos ?? 0);
    if (totalProductos > 0) {
      const cantidad = Math.max(1, Number(registro.cantidadProductosVendidos ?? 0));
      rows.push({
        ...base,
        tipo: 'Producto',
        concepto: 'Productos',
        cantidad,
        precioUnitario: round2(totalProductos / cantidad),
        subtotal: totalProductos,
      });
    }
  }

  return rows;
}

/**
 * Period fiado aggregates. Generated uses the immutable `montoFiado` snapshot
 * with a legacy fallback to the current `montoPendiente`; collected is the part
 * already paid for that same fiado (clamped at 0) so `generado = cobrado +
 * pendiente` holds for consistent data.
 */
export function resumenFiadoDeRegistros(registros: RegistroServicioEntity[]): FiadoResumen {
  let generado = 0;
  let cobrado = 0;
  let pendiente = 0;

  for (const registro of registros) {
    if (registro.estado === EstadoRegistro.ANULADO) continue;

    const pend = Math.max(0, Number(registro.montoPendiente ?? 0));
    const fiado = Math.max(
      0,
      registro.montoFiado != null ? Number(registro.montoFiado) : pend,
    );

    generado += fiado;
    cobrado += Math.max(0, fiado - pend);
    pendiente += pend;
  }

  return {
    generado: round2(generado),
    cobrado: round2(cobrado),
    pendiente: round2(pendiente),
  };
}

function estiloHeader(cell: ExcelJS.Cell) {
  cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  cell.fill = HEADER_FILL;
  cell.alignment = { vertical: 'middle' };
}

@injectable()
export class ExcelExportService {
  constructor(
    @inject(PyLMensualUseCase)
    private readonly pylMensualUseCase: PyLMensualUseCase,
    @inject('IRegistroServicioRepository')
    private readonly registroRepo: IRegistroServicioRepository,
    @inject(TypeORMPagoPeriodoRepository)
    private readonly pagoPeriodoRepo: TypeORMPagoPeriodoRepository,
  ) {}

  /**
   * Orquesta el P&L, los movimientos del período y el resumen de fiado y
   * devuelve el workbook listo. Puro (sin I/O): los tests pueden inspeccionar
   * las hojas directamente.
   */
  buildPyLWorkbook(
    pyl: PyLMensualOutput,
    movimientos: RegistroMovimiento[],
    fiado?: FiadoResumen,
    cobros: PagoPeriodoDTO[] = [],
  ): ExcelJS.Workbook {
    const workbook = new ExcelJS.Workbook();
    const pylSheet = workbook.addWorksheet('P&L');
    const movSheet = workbook.addWorksheet('Movimientos');
    const cobrosSheet = workbook.addWorksheet('Cobros del período');

    // ── Hoja P&L: resumen por concepto ──
    pylSheet.columns = [{ width: 40 }, { width: 18 }];
    const pylHeader = pylSheet.addRow(PYL_HEADER);
    pylHeader.eachCell((cell) => estiloHeader(cell));
    pylSheet.getRow(1).height = 20;

    const conceptos: Array<[string, string | number]> = [
      ['Período', `${pyl.desde} a ${pyl.hasta}`],
      ['Incrementos', pyl.incrementos ?? 0],
      ['Ingresos netos', pyl.ingresosNetos],
      ['Total servicios', pyl.totalServicios],
      ['Total productos', pyl.totalProductos],
      ['Propinas', pyl.propinas],
      ['Cobrado', pyl.cobrado],
      ['Deudas por cobrar', pyl.deudasPorCobrar],
      ['Insumos (costo base)', pyl.costoBaseInsumos],
      ['Costo de productos vendidos', pyl.costoProductos],
      ['Margen bruto', pyl.margenBruto],
      ['Comisiones', pyl.comisiones],
      ['Gastos fijos', pyl.gastosFijos],
      ['Gastos operativos', pyl.gastosOperativos],
    ];
    // Una fila por categoría de gasto, si existe
    for (const [categoria, monto] of Object.entries(pyl.gastosPorCategoria ?? {})) {
      conceptos.push([`Gastos por categoría — ${categoria}`, monto]);
    }
    conceptos.push(['Total gastos', pyl.totalGastos]);
    conceptos.push(['Compras de inventario (no es gasto)', pyl.comprasInventario]);
    conceptos.push(['Devoluciones', pyl.devoluciones]);
    conceptos.push(['Utilidad neta', pyl.utilidadNeta]);

    for (const [concepto, valor] of conceptos) {
      const row = pylSheet.addRow([concepto, valor]);
      // Formato COP solo para filas numéricas (el período es texto)
      if (typeof valor === 'number') {
        row.getCell(2).numFmt = COP_FORMAT;
      }
      if (concepto === 'Utilidad neta') {
        row.font = { bold: true };
      }
    }

    // ── Bloque FIADO del período ──
    // Backward-compatible default: callers that don't compute the snapshot
    // aggregate still get a coherent block based on the P&L pending amount.
    const fiadoResumen: FiadoResumen =
      fiado ?? { generado: pyl.fiadoPeriodo, cobrado: 0, pendiente: pyl.fiadoPeriodo };

    pylSheet.addRow([]);
    const fiadoSection = pylSheet.addRow(['FIADO DEL PERÍODO', '']);
    fiadoSection.font = { bold: true, color: { argb: 'FF92400E' } };
    fiadoSection.fill = FIADO_SECTION_FILL;

    const fiadoRows: Array<[string, number]> = [
      ['Fiado generado', fiadoResumen.generado],
      ['Cobrado del fiado', fiadoResumen.cobrado],
      ['Fiado por cobrar', fiadoResumen.pendiente],
    ];
    for (const [concepto, valor] of fiadoRows) {
      const row = pylSheet.addRow([concepto, valor]);
      row.getCell(2).numFmt = COP_FORMAT;
    }
    const totalFiado = pylSheet.addRow([
      'Total fiado (cobrado + por cobrar)',
      round2(fiadoResumen.cobrado + fiadoResumen.pendiente),
    ]);
    totalFiado.getCell(2).numFmt = COP_FORMAT;
    totalFiado.font = { bold: true };

    // ── Hoja Movimientos: detalle por línea de venta ──
    movSheet.columns = [
      { width: 12 }, // Fecha
      { width: 24 }, // Cliente
      { width: 22 }, // Empleada
      { width: 11 }, // Tipo
      { width: 28 }, // Concepto
      { width: 10 }, // Cantidad
      { width: 15 }, // Precio unitario
      { width: 15 }, // Subtotal
      { width: 15 }, // Total venta
      { width: 17 }, // Pagado al vender
      { width: 16 }, // Cobrado después
      { width: 15 }, // Fiado
      { width: 15 }, // Pendiente
      { width: 14 }, // Estado cobro
      { width: 20 }, // Fecha del último cobro
    ];
    const movHeader = movSheet.addRow(MOVIMIENTOS_HEADER);
    movHeader.eachCell((cell) => estiloHeader(cell));
    movSheet.getRow(1).height = 20;

    for (const m of movimientos) {
      const row = movSheet.addRow([
        m.fecha,
        m.cliente,
        m.empleada,
        m.tipo,
        m.concepto,
        m.cantidad,
        m.precioUnitario,
        m.subtotal,
        m.totalVenta,
        m.montoPagadoAlVender,
        m.montoCobradoDespues,
        m.montoFiado,
        m.montoPendiente,
        m.estadoCobro,
        m.fechaUltimoCobro,
      ]);
      // COP format on price/subtotal/total/paid-at-sale/collected-later/fiado/pending.
      for (const col of [7, 8, 9, 10, 11, 12, 13]) {
        row.getCell(col).numFmt = COP_FORMAT;
      }
      row.getCell(14).font = { bold: true, color: { argb: ESTADO_COBRO_COLOR[m.estadoCobro] } };
    }

    // ── Cobros del período sheet: one row per PAYMENT received in the period ──
    // Same basis as the P&L "Cobrado" line (payment business date), so the
    // TOTAL reconciles with the period's collected income.
    cobrosSheet.columns = [
      { width: 16 }, // Fecha de cobro
      { width: 10 }, // Venta #
      { width: 24 }, // Cliente
      { width: 22 }, // Empleada
      { width: 18 }, // Método de pago
      { width: 15 }, // Monto
    ];
    const cobrosHeader = cobrosSheet.addRow(COBROS_HEADER);
    cobrosHeader.eachCell((cell) => estiloHeader(cell));
    cobrosSheet.getRow(1).height = 20;

    let totalCobros = 0;
    for (const cobro of cobros) {
      totalCobros += Number(cobro.monto ?? 0);
      const row = cobrosSheet.addRow([
        cobro.fechaCobro,
        cobro.registroId,
        cobro.cliente,
        cobro.empleada,
        cobro.metodoPago,
        cobro.monto,
      ]);
      row.getCell(6).numFmt = COP_FORMAT;
    }
    const totalRow = cobrosSheet.addRow(['TOTAL', '', '', '', '', round2(totalCobros)]);
    totalRow.getCell(6).numFmt = COP_FORMAT;
    totalRow.font = { bold: true };

    return workbook;
  }

  /** Ejecuta el P&L + movimientos del período y serializa el workbook a Buffer. */
  async exportar(input: PyLMensualInput & { salonId: number }): Promise<{ buffer: Buffer; filename: string }> {
    const hoy = getColombiaDateString();
    const desde = input.desde ?? `${hoy.slice(0, 7)}-01`;
    const hasta = input.hasta ?? hoy;

    const inicio = colombiaDayStartUTC(desde);
    const fin = colombiaDayEndUTC(hasta);

    const [pyl, registros, cobros] = await Promise.all([
      this.pylMensualUseCase.execute({
        salonId: input.salonId,
        desde,
        hasta,
        ...(input.usuarioId !== undefined ? { usuarioId: input.usuarioId } : {}),
        ...(input.clienteId !== undefined ? { clienteId: input.clienteId } : {}),
      }),
      this.registroRepo.search({
        salonId: input.salonId,
        desde: inicio,
        hasta: fin,
        ...(input.usuarioId !== undefined ? { usuarioId: input.usuarioId } : {}),
        ...(input.clienteId !== undefined ? { clienteId: input.clienteId } : {}),
      }),
      this.pagoPeriodoRepo.findBySalonAndPeriodo({
        salonId: input.salonId,
        desde,
        hasta,
        ...(input.usuarioId !== undefined ? { usuarioId: input.usuarioId } : {}),
        ...(input.clienteId !== undefined ? { clienteId: input.clienteId } : {}),
      }),
    ]);

    const activos = registros.filter((r) => r.estado !== EstadoRegistro.ANULADO);
    const movimientos = activos.flatMap(registroAMovimientos);
    const fiado = resumenFiadoDeRegistros(activos);

    const workbook = this.buildPyLWorkbook(pyl, movimientos, fiado, cobros);
    // exceljs devuelve su propio tipo Buffer (extends ArrayBuffer); convertirlo
    // al Buffer de Node para que Express pueda enviarlo como binario.
    const buffer = Buffer.from(await workbook.xlsx.writeBuffer());
    const filename = `pyl_${desde}_${hasta}.xlsx`;

    return { buffer, filename };
  }
}
